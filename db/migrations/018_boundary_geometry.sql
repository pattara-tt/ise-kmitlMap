-- ไม่เขียนทับพิกัดที่ฝ่ายทะเบียน/GIS แก้ไว้แล้ว (แก้เฉพาะแถวที่ geometry ว่างหรือใช้ไม่ได้)

BEGIN;

-- 1) ถ้า MB-01 (ขอบเขตวิทยาเขต) ถูกใส่พิกัดของอาคาร Sc8 ผิดแถว ให้เคลียร์กลับเป็น NULL
UPDATE map_boundaries
SET geometry = NULL
WHERE id = 'MB-01'
  AND type = 'campus'
  AND geometry = '[
  [13.7314817, 100.7708228],
  [13.7282925, 100.7709301],
  [13.7287928, 100.7900489],
  [13.7314192, 100.7898773],
  [13.7314817, 100.7708228]
]'::jsonb;

-- 2) ใส่พิกัดให้ MB-02 (อาคาร Sc8) เฉพาะเมื่อยังไม่มีพิกัดที่ใช้ได้ (ต้องเป็น array อย่างน้อย 3 จุด)
UPDATE map_boundaries
SET geometry = '[[13.7292248,100.779662],[13.7290841,100.779662],[13.7290893,100.77978],[13.7289799,100.7797746],[13.7289903,100.7800268],[13.7289382,100.7799785],[13.7288235,100.7799678],[13.7288288,100.7803165],[13.7291987,100.7803004],[13.7292248,100.7801448],[13.7291831,100.7801341],[13.7291883,100.7800858],[13.7292248,100.7800858]]'::jsonb
WHERE id = 'MB-02'
  AND type = 'building'
  AND (
    geometry IS NULL
    OR jsonb_typeof(geometry) <> 'array'
    OR (CASE WHEN jsonb_typeof(geometry) = 'array'
             THEN jsonb_array_length(geometry) < 3
             ELSE FALSE END)
  );

COMMIT;